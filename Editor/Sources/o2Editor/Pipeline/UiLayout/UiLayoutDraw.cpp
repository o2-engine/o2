    // The characters of a caption the pixel font draws: non-ASCII letters it has a look-alike for, '?' for the rest
    static std::vector<char> CaptionChars(const String& text)
    {
        std::vector<char> out;
        for (int i = 0; i < text.Length(); i++)
        {
            unsigned char c = (unsigned char)text[i];
            if (c < 0x80)
            {
                out.push_back(c >= 0x20 && c < 0x7F ? (char)c : '?');
                continue;
            }

            if (c == 0xCE && i + 1 < text.Length() && (unsigned char)text[i + 1] == 0x94) out.push_back('D');
            else if (c == 0xC3 && i + 1 < text.Length() && (unsigned char)text[i + 1] == 0x97) out.push_back('x');
            else if (c == 0xC2 && i + 1 < text.Length() && (unsigned char)text[i + 1] == 0xB7) out.push_back('.');
            else if (c == 0xE2 && i + 2 < text.Length() && (unsigned char)text[i + 1] == 0x86 && (unsigned char)text[i + 2] == 0x92) out.push_back('>');
            else if (c >= 0xC0)
                out.push_back('?');

            while (i + 1 < text.Length() && ((unsigned char)text[i + 1] & 0xC0) == 0x80)
                i++;
        }
        return out;
    }

    void DrawCaption(UiImage& img, const String& text, double x, double y, const Rgb& rgb, int size /*= 11*/)
    {
        int scale = size >= 12 ? 2 : 1;
        auto chars = CaptionChars(text);
        int ox = (int)JsRound(x), oy = (int)JsRound(y);
        UInt8 fg[3] = { Clamp8(rgb.r), Clamp8(rgb.g), Clamp8(rgb.b) };

        auto plot = [&](int px, int py, const UInt8* color)
        {
            if (px < 0 || py < 0 || px >= img.w || py >= img.h)
                return;
            UInt8* p = img.At(px, py);
            p[0] = color[0]; p[1] = color[1]; p[2] = color[2]; p[3] = 255;
        };

        static const UInt8 black[3] = { 0, 0, 0 };
        for (int pass = 0; pass < 2; pass++)
        {
            for (size_t i = 0; i < chars.size(); i++)
            {
                const UInt8* glyph = font5x7[chars[i] - 0x20];
                int gx = ox + (int)i*6*scale;
                for (int col = 0; col < 5; col++)
                {
                    for (int row = 0; row < 7; row++)
                    {
                        if (!(glyph[col] & (1 << row)))
                            continue;

                        for (int sy = 0; sy < scale; sy++)
                        {
                            for (int sx = 0; sx < scale; sx++)
                            {
                                int px = gx + col*scale + sx, py = oy + row*scale + sy;
                                if (pass == 0)
                                {
                                    for (int dy = -1; dy <= 1; dy++)
                                        for (int dx = -1; dx <= 1; dx++)
                                            plot(px + dx, py + dy, black);
                                }
                                else
                                    plot(px, py, fg);
                            }
                        }
                    }
                }
            }
        }
    }

    UiImage Strip(const Vector<StripEntry>& entries, int gap /*= 8*/)
    {
        int h = 0, w = 0;
        for (auto& e : entries)
        {
            h = Math::Max(h, e.img.h);
            w += e.img.w;
        }
        h += 22;
        w += gap*Math::Max(0, entries.Count() - 1);

        UiImage out = UiImage::Blank(w, h, 24, 26, 32, 255);
        int x = 0;
        for (auto& e : entries)
        {
            out.Blit(e.img, x, 22);
            DrawCaption(out, e.title, x + 4, 5, Rgb(235, 235, 240), 12);
            x += e.img.w + gap;
        }
        return out;
    }

    Rgb KindColor(const String& kind)
    {
        if (kind == "panel") return Rgb(255, 80, 80);
        if (kind == "image") return Rgb(70, 170, 255);
        if (kind == "button") return Rgb(60, 220, 90);
        if (kind == "text") return Rgb(255, 80, 255);
        if (kind == "progress") return Rgb(255, 160, 40);
        if (kind == "group") return Rgb(160, 160, 160);
        if (kind == "grid") return Rgb(255, 230, 60);
        if (kind == "input") return Rgb(120, 240, 230);
        return Rgb(255, 255, 255);
    }
