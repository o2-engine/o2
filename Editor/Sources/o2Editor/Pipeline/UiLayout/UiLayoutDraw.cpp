    void StrokeRect(UiImage& img, const Box& b, const Rgb& rgb, int width /*= 1*/)
    {
        int x0 = (int)JsRound(b.x), y0 = (int)JsRound(b.y), x1 = (int)JsRound(b.x + b.w) - 1, y1 = (int)JsRound(b.y + b.h) - 1;
        auto put = [&](int x, int y)
        {
            if (x < 0 || y < 0 || x >= img.w || y >= img.h)
                return;
            UInt8* p = img.At(x, y);
            p[0] = Clamp8(rgb.r); p[1] = Clamp8(rgb.g); p[2] = Clamp8(rgb.b); p[3] = 255;
        };

        for (int k = 0; k < width; k++)
        {
            for (int x = x0; x <= x1; x++) { put(x, y0 + k); put(x, y1 - k); }
            for (int y = y0; y <= y1; y++) { put(x0 + k, y); put(x1 - k, y); }
        }
    }

